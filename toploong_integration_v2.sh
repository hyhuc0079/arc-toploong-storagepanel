#!/bin/sh
# TOPLOONG V2 integration trial. Arc Config Mode only. No disk writes.
set -eu
P3=${TOPLOONG_P3:-/mnt/p3}
BACKUP="$P3/toploong-integration-backup-v2"
fail() { echo "ERROR: $*" >&2; exit 1; }
hash() { sha256sum "$1" | awk '{print $1}'; }
[ "$(id -u)" = 0 ] || fail 'root required'
[ ! -e /etc/user_model.dts ] || fail 'Run in Arc Config Mode, not DSM'
[ -d "$P3/addons" ] && [ -d "$P3/users" ] || fail 'Arc partition missing'
ACTION=${1:-check}
case "$ACTION" in check|apply|restore) ;; *) fail 'usage: sh toploong_integration_v2.sh check|apply|restore' ;; esac
D=$(find "$P3/addons" -type f -path '*/disks/all.tgz' -print)
P=$(find "$P3/addons" -type f -path '*/storagepanel/all.tgz' -print)
[ -f "$D" ] && [ -f "$P" ] || fail 'Cannot locate exactly one archive for each addon'
[ ! -e "$P3/users/model.dts" ] && [ ! -e "$P3/users/SA6400.dts" ] || fail 'Static DTS still present; stop'
W=$(mktemp -d /tmp/toploong-integrate.XXXXXX)
trap 'rm -rf "$W"' EXIT
mkdir "$W/disks" "$W/panel" "$W/payload"
# Archive integrity and regular file paths are checked before mutation.
tar -xzf "$D" -C "$W/disks"
tar -xzf "$P" -C "$W/panel"
DS="$W/disks/root/usr/bin/disks.sh"
DI="$W/disks/install.sh"
PS="$W/panel/root/usr/bin/storagepanel.sh"
PI="$W/panel/install.sh"
for f in "$DS" "$DI" "$PS" "$PI"; do [ -f "$f" ] && [ ! -L "$f" ] || fail "Unexpected archive layout: $f"; done
if [ "$ACTION" = restore ]; then
  [ -f "$BACKUP/disks.tgz" ] && [ -f "$BACKUP/panel.tgz" ] && [ -f "$BACKUP/hashes" ] || fail 'V2 backup incomplete'
  [ "$(cat "$BACKUP/disks.path")" = "$D" ] && [ "$(cat "$BACKUP/panel.path")" = "$P" ] || fail 'Backup path mismatch'
  read old_d old_p new_d new_p < "$BACKUP/hashes"
  [ "$(hash "$D")" = "$new_d" ] && [ "$(hash "$P")" = "$new_p" ] || fail 'Addon changed since install; refusing rollback'
  [ "$(hash "$BACKUP/disks.tgz")" = "$old_d" ] && [ "$(hash "$BACKUP/panel.tgz")" = "$old_p" ] || fail 'Backup hash mismatch'
  cp -p "$BACKUP/disks.tgz" "$D.toploong-new"
  cp -p "$BACKUP/panel.tgz" "$P.toploong-new"
  mv -f "$D.toploong-new" "$D"
  if ! mv -f "$P.toploong-new" "$P"; then fail 'Partial rollback: inspect archives before rebuilding'; fi
  sync
  echo 'RESTORE OK: disks V1 and stock storagepanel archives restored. Rebuild Loader.'
  exit 0
fi
[ "$(hash "$DS")" = 8846382e78d427ad25ece764de096a9f3aa85abffb0888f75ccd503d76e150f1 ] || fail 'Expected installed Dynamic Disks V1 source not found'
[ "$(hash "$DI")" = bf75c9c1a0394d51fe66e8df722be1ae9a2136eb82cb1980fb7d692e5825fe54 ] || fail 'Disks addon install.sh mismatch'
[ "$(hash "$PS")" = 8ee4c80c8720fa1382d336c8fc2f8a184c47d57c0ff98e049ed760f61f270a3b ] || fail 'StoragePanel generator version mismatch'
[ "$(grep -Fc 'cp -pf /usr/bin/storagepanel.sh /tmpRoot/usr/bin/storagepanel.sh' "$PI")" = 1 ] || fail 'StoragePanel addon copy anchor mismatch'
[ "$(grep -Fc 'ExecStart=/usr/bin/storagepanel.sh' "$PI")" = 1 ] || fail 'StoragePanel unit anchor mismatch'
[ ! -e "$BACKUP" ] || fail 'V2 backup already exists; inspect before reinstalling'
[ ! -e "$D.toploong-new" ] && [ ! -e "$P.toploong-new" ] || fail 'Stale staging file exists'
echo "Disks V1 verified: $D"
echo "StoragePanel stock verified: $P"
base64 -d <<'TOPLOONG_V2_PAYLOAD' | tar -xzf - -C "$W/payload"
