#!/bin/sh
# TOPLOONG dynamic mapping trial installer for the user's exact Arc disks addon.
# Run ONLY in Arc Config Mode, never DSM. No disk/RAID writes, no rebuild/reboot.
set -eu
P3=${TOPLOONG_P3:-/mnt/p3}
BACKUP="$P3/toploong-dynamic-backup-v1"
STATIC="$P3/users/SA6400.dts"
ORIG=bff02d9832dd9b7a7505808e23df1e15ce87a1ef23f4894a1099e3f36f54fcd4
PATCHED=8846382e78d427ad25ece764de096a9f3aa85abffb0888f75ccd503d76e150f1
DTS=abd962b90565895051bd7fef2a752b97885d318cf53422b0c5b23f77beabd6c7
fail() { echo "ERROR: $*" >&2; exit 1; }
hash() { sha256sum "$1" | awk '{print $1}'; }
[ "$(id -u)" = 0 ] || fail 'root required'
[ ! -e /etc/user_model.dts ] || fail 'Run in Arc Config Mode, not DSM'
[ -d "$P3/addons" ] && [ -d "$P3/users" ] || fail 'Arc partition directories not found'
ACTION=${1:-check}
case "$ACTION" in check|apply|restore) ;; *) fail 'usage: sh script [check|apply|restore] [path/to/disks/all.tgz]' ;; esac
if [ $# -ge 2 ]; then
    ARCHIVE=$(readlink -f "$2")
else
    ARCHIVE=$(find "$P3/addons" -type f -path '*/disks/all.tgz' -print)
fi
[ -n "$ARCHIVE" ] && [ -f "$ARCHIVE" ] || fail 'Cannot locate exactly one disks/all.tgz; inspect Arc addon directory'
case "$ARCHIVE" in "$P3"/addons/*/all.tgz) ;; *) fail 'Unexpected addon path' ;; esac
WORK=$(mktemp -d /tmp/toploong-addon.XXXXXX)
trap 'rm -rf "$WORK"' EXIT
mkdir "$WORK/extract"
# Inspect the existing archive, not a downloaded replacement of unknown version.
tar -xzf "$ARCHIVE" -C "$WORK/extract"
S="$WORK/extract/root/usr/bin/disks.sh"
I="$WORK/extract/install.sh"
[ -f "$S" ] && [ ! -L "$S" ] && [ -f "$I" ] || fail 'Unexpected disks addon archive layout'
ACTUAL=$(hash "$S")
echo "Archive: $ARCHIVE"
echo "disks.sh SHA256: $ACTUAL"
if [ "$ACTION" = restore ]; then
    [ -f "$BACKUP/all.tgz" ] && [ -f "$BACKUP/SA6400.dts" ] && [ -f "$BACKUP/archive.path" ] || fail 'Backup incomplete'
    [ "$(cat "$BACKUP/archive.path")" = "$ARCHIVE" ] || fail 'Backup path mismatch'
    [ "$ACTUAL" = "$PATCHED" ] || fail 'Current archive is not this patch; do not overwrite an updated addon'
    [ ! -e "$STATIC" ] && [ ! -e "$P3/users/model.dts" ] || fail 'Another DTS exists; inspect manually before restore'
    [ "$(hash "$BACKUP/SA6400.dts")" = "$DTS" ] || fail 'Backup DTS mismatch'
    [ "$(hash "$BACKUP/all.tgz")" = "$(cat "$BACKUP/archive.sha256")" ] || fail 'Backup archive mismatch'
    cp -p "$BACKUP/all.tgz" "$ARCHIVE.toploong-new"
    cp -p "$BACKUP/SA6400.dts" "$STATIC"
    mv -f "$ARCHIVE.toploong-new" "$ARCHIVE"
    sync
    echo 'RESTORE OK. Rebuild Loader before booting DSM.'
    exit 0
fi
[ "$ACTUAL" = "$ORIG" ] || fail 'Original script hash mismatch; do not force installation'
[ "$(hash "$I")" = bf75c9c1a0394d51fe66e8df722be1ae9a2136eb82cb1980fb7d692e5825fe54 ] || fail 'Original addon install.sh hash mismatch'
[ -f "$STATIC" ] && [ "$(hash "$STATIC")" = "$DTS" ] || fail 'Expected SA6400.dts is missing or different'
[ ! -e "$P3/users/model.dts" ] || fail 'Generic model.dts also present; inspect it first'
[ ! -e "$BACKUP" ] || fail 'Backup directory exists; refusing to overwrite'
[ ! -e "$ARCHIVE.toploong-new" ] || fail 'Stale temporary archive exists'
echo 'CHECK OK: exact tested source and static DTS found.'
[ "$ACTION" = apply ] || exit 0
# Payload: exact local source with the TOPLOONG dynamic mapping patch.
base64 -d <<'TOPLOONG_PAYLOAD' | gzip -dc > "$WORK/patched.sh"
